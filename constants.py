# -- JavaScript для извлечения карточек из DOM --------------------------------
#
# ИСПРАВЛЕНИЕ: селектор названия изменён с '.text .title span span'
# на '.text .title'.
#
# Причина: когда CloudShop подсвечивает найденное слово, он разбивает
# содержимое span на несколько дочерних span-ов. Старый селектор
# 'span span' брал только ПЕРВЫЙ фрагмент (например "Настольная игра: "),
# а не полное название. Теперь берём textContent всего блока .title,
# который склеивает текст всех вложенных узлов автоматически.
#
# Все комментарии внутри JS намеренно на ASCII -- избегаем
# проблем с кодировкой при разборе строки Playwright.
#
EXTRACT_JS = """() => {
    var results = [];
    var cards = document.querySelectorAll('.catalog-card');

    for (var i = 0; i < cards.length; i++) {
        var card = cards[i];

        // Title: read the whole .title block to get full text
        // even when search highlighting splits it into multiple spans.
        var titleEl = card.querySelector('.text .title');
        var name = titleEl ? titleEl.textContent.trim() : '';
        if (!name) { continue; }

        // Stock: '<span>1 sht</span>' -> number
        var stockEl = card.querySelector('.stock span');
        var stockText = stockEl ? stockEl.textContent.trim() : '0';
        var m = stockText.match(/([0-9]+)/);
        var qty = m ? parseInt(m[1], 10) : 0;

        // Price: '<div class="price">739 000,00 UZS</div>'
        var priceEl = card.querySelector('.price');
        var price = priceEl ? priceEl.textContent.trim() : '';

        results.push({ name: name, qty: qty, price: price });
    }
    return results;
}"""

